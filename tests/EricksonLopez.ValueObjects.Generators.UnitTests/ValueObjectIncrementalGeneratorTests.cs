    [Fact]
    [System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage("Trimming", "IL2075:DynamicallyAccessedMembers")]
    [System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage("Trimming", "IL2072:DynamicallyAccessedMembers")]
    public void GeneratedCode_ShouldCompile_AndExecuteAllGeneratedMethodsCorrectly()
    {
        var userSource = """
        namespace ExecutionDomain;


        [ValueObject(GenerateConversionOperators = true)]
        public readonly partial record struct ItemSku
        {
            public string Value { get; init; }

            public static EricksonLopez.Result.Result<ItemSku> Create(string value) =>
                !string.IsNullOrWhiteSpace(value) && value != "invalid"
                    ? EricksonLopez.Result.Result.Success(new ItemSku { Value = value })
                    : EricksonLopez.Result.Result.Failure<ItemSku>(EricksonLopez.Result.Error.Validation("InvalidSku", "SKU must not be empty or 'invalid'."));

            public static string TestSpanParse(string s) => Parse(System.MemoryExtensions.AsSpan(s), null).Value;
            public static bool TestSpanTryParse(string s, out ItemSku res) => TryParse(System.MemoryExtensions.AsSpan(s), null, out res);
        }
        """;

        var (outputCompilation, generatedSources, diagnostics) = RunGenerator(userSource);
        diagnostics.Should().BeEmpty();

        using var ms = new MemoryStream();
        var emitResult = outputCompilation.Emit(ms);
        var errors = emitResult.Diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error).Select(d => d.ToString()).ToList();
        emitResult.Success.Should().BeTrue(string.Join(Environment.NewLine, errors));

        var assembly = Assembly.Load(ms.ToArray());
        var skuType = assembly.GetType("ExecutionDomain.ItemSku")!;
        skuType.Should().NotBeNull();

        // 1. IParsable string Parse(string, IFormatProvider)
        var parseMethod = skuType.GetMethod("Parse", [typeof(string), typeof(IFormatProvider)]);
        parseMethod.Should().NotBeNull();

        var parsed = parseMethod!.Invoke(null, ["SKU-100", null]);
        parsed.Should().NotBeNull();
        skuType.GetProperty("Value")!.GetValue(parsed).Should().Be("SKU-100");

        // Parse null string throws ArgumentNullException
        var parseNull = () => parseMethod.Invoke(null, [null, null]);
        parseNull.Should().Throw<TargetInvocationException>().WithInnerException<ArgumentNullException>();

        // Parse invalid string throws FormatException
        var parseInvalid = () => parseMethod.Invoke(null, ["invalid", null]);
        parseInvalid.Should().Throw<TargetInvocationException>().WithInnerException<FormatException>()
            .WithMessage("Cannot parse 'invalid' as ItemSku: SKU must not be empty or 'invalid'.");

        // 2. IParsable TryParse(string, IFormatProvider, out T)
        var tryParseMethod = skuType.GetMethod("TryParse", [typeof(string), typeof(IFormatProvider), skuType.MakeByRefType()]);
        tryParseMethod.Should().NotBeNull();

