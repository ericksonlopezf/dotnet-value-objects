        object?[] spanArgsFail = ["invalid", null];
        var spanFailResult = (bool)testSpanTryParse.Invoke(null, spanArgsFail)!;
        spanFailResult.Should().BeFalse();

        // 5. Explicit Operators
        var opExplicitToString = skuType.GetMethods(BindingFlags.Public | BindingFlags.Static)
            .FirstOrDefault(m => m.Name == "op_Explicit" && m.ReturnType == typeof(string));
        opExplicitToString.Should().NotBeNull();
        var strVal = opExplicitToString!.Invoke(null, [parsed]);
        strVal.Should().Be("SKU-100");

        var opExplicitToVo = skuType.GetMethods(BindingFlags.Public | BindingFlags.Static)
            .FirstOrDefault(m => m.Name == "op_Explicit" && m.ReturnType == skuType);
        opExplicitToVo.Should().NotBeNull();
        var voVal = opExplicitToVo!.Invoke(null, ["SKU-500"]);
        skuType.GetProperty("Value")!.GetValue(voVal).Should().Be("SKU-500");

        // 6. System.Text.Json Serialization & Deserialization
        var jsonConverterType = assembly.GetType("ExecutionDomain.ItemSku+ItemSkuJsonConverter")
            ?? assembly.GetType("ExecutionDomain.ItemSkuJsonConverter");
        jsonConverterType.Should().NotBeNull();

        var jsonOptions = new JsonSerializerOptions();
        var converterInstance = (JsonConverter)Activator.CreateInstance(jsonConverterType!)!;
        jsonOptions.Converters.Add(converterInstance);

        var json = JsonSerializer.Serialize(parsed, jsonOptions);
        json.Should().Be("\"SKU-100\"");

        var deserialized = JsonSerializer.Deserialize(json, skuType, jsonOptions);
        skuType.GetProperty("Value")!.GetValue(deserialized).Should().Be("SKU-100");

        var actNullJson = () => JsonSerializer.Deserialize("null", skuType, jsonOptions);
        actNullJson.Should().Throw<JsonException>();

        var actInvalidJson = () => JsonSerializer.Deserialize("\"invalid\"", skuType, jsonOptions);
        actInvalidJson.Should().Throw<JsonException>();
