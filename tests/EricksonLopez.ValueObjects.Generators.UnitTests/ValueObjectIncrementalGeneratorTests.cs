    [Fact]
    public void Generator_ShouldGenerateCode_ForRecordStruct()
    {
        var userSource = """
        namespace MyDomain;

        using EricksonLopez.ValueObjects;

        [ValueObject]
        public readonly partial record struct OrderId
        {
            public static EricksonLopez.Result.Result<OrderId> Create(string value) =>
                string.IsNullOrEmpty(value) ? EricksonLopez.Result.Result.Failure<OrderId>(EricksonLopez.Result.Error.Validation("Empty")) : EricksonLopez.Result.Result.Success(new OrderId());
        }
        """;

        var (outputCompilation, generatedSources, diagnostics) = RunGenerator(userSource);

        diagnostics.Should().BeEmpty();
        generatedSources.Should().HaveCount(1);
        var generated = generatedSources.First();
        generated.HintName.Should().Be("OrderId_ValueObject.g.cs");
        var code = generated.SourceText.ToString().Replace("\r\n", "\n");
        code.Should().Contain("// <auto-generated/>\n#nullable enable\n\nnamespace MyDomain\n{\n");
        code.Should().Contain("[global::System.Text.Json.Serialization.JsonConverter(typeof(OrderIdJsonConverter))]");
        code.Should().Contain("readonly partial record struct OrderId : global::System.IParsable<OrderId>, global::System.ISpanParsable<OrderId>, global::EricksonLopez.ValueObjects.IValueObject<OrderId>");
        code.Should().Contain("public static OrderId Parse(string s, global::System.IFormatProvider? provider = null)");
        code.Should().Contain("public static bool TryParse(string? s, global::System.IFormatProvider? provider, out OrderId result)");
        code.Should().Contain("public static OrderId Parse(global::System.ReadOnlySpan<char> s, global::System.IFormatProvider? provider = null)");
        code.Should().Contain("public static bool TryParse(global::System.ReadOnlySpan<char> s, global::System.IFormatProvider? provider, out OrderId result)");
        code.Should().Contain("public sealed class OrderIdJsonConverter : global::System.Text.Json.Serialization.JsonConverter<OrderId>");
        code.Should().NotContain("operator");
    }

