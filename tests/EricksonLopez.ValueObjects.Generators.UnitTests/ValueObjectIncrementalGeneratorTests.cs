        var successResult = (bool)tryParseMethod!.Invoke(null, tryParseArgsSuccess)!;
        successResult.Should().BeTrue();
        skuType.GetProperty("Value")!.GetValue(tryParseArgsSuccess[2]).Should().Be("SKU-200");

        object?[] tryParseArgsNull = [null, null, null];
        var nullResult = (bool)tryParseMethod.Invoke(null, tryParseArgsNull)!;
        nullResult.Should().BeFalse();

        object?[] tryParseArgsFail = ["invalid", null, null];
        var failResult = (bool)tryParseMethod.Invoke(null, tryParseArgsFail)!;
        failResult.Should().BeFalse();

        // 3. ISpanParsable ReadOnlySpan<char> Parse(ReadOnlySpan<char>, IFormatProvider)
        var testSpanParse = skuType.GetMethod("TestSpanParse", [typeof(string)]);
        testSpanParse.Should().NotBeNull();

        var spanParsed = testSpanParse!.Invoke(null, ["SKU-300"]);
        spanParsed.Should().Be("SKU-300");

        var parseSpanInvalid = () => testSpanParse.Invoke(null, ["invalid"]);
        parseSpanInvalid.Should().Throw<TargetInvocationException>().WithInnerException<FormatException>()
            .WithMessage("Cannot parse 'invalid' as ItemSku: SKU must not be empty or 'invalid'.");

        // 4. ISpanParsable TryParse(ReadOnlySpan<char>, IFormatProvider, out T)
        var testSpanTryParse = skuType.GetMethod("TestSpanTryParse", [typeof(string), skuType.MakeByRefType()]);
        testSpanTryParse.Should().NotBeNull();

